begin;

create schema laundry_private;
revoke all on schema laundry_private from public, anon, authenticated;

create table public.staff_profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null check (char_length(btrim(display_name)) between 1 and 100),
  role text not null check (role in ('employee', 'manager')),
  active boolean not null default true
);

create table public.services (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(btrim(name)) between 1 and 120),
  price numeric(12, 2) not null check (price > 0 and price <= 1000000),
  is_active boolean not null default true
);

create table public.addons (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(btrim(name)) between 1 and 120),
  price numeric(12, 2) not null check (price >= 0 and price <= 1000000),
  is_active boolean not null default true
);

create sequence laundry_private.claim_numbers;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default ('L-' || nextval('laundry_private.claim_numbers')::text),
  customer_name text not null check (char_length(btrim(customer_name)) between 1 and 120),
  customer_phone text check (char_length(customer_phone) <= 40),
  pickup_at timestamptz,
  notes text check (char_length(notes) <= 2000),
  total numeric(12, 2) not null check (total > 0 and total < 10000000000),
  payment_status boolean not null default false,
  status text not null default 'pending' check (status in ('pending', 'done', 'released', 'cancelled')),
  created_at timestamptz not null default now(),
  created_by uuid not null,
  created_by_email text,
  updated_at timestamptz not null default now(),
  search_text text generated always as (
    customer_name || ' ' || coalesce(customer_phone, '') || ' '
      || regexp_replace(coalesce(customer_phone, ''), '[^0-9]', '', 'g') || ' ' || order_number
  ) stored
);

create index orders_recent_idx on public.orders (created_at desc, id desc);
create index orders_status_recent_idx on public.orders (status, created_at desc, id desc);

create table public.order_items (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id),
  service_id bigint not null references public.services (id),
  service_name text not null,
  price numeric(12, 2) not null,
  quantity integer not null check (quantity between 1 and 1000),
  unique (order_id, service_id)
);

create table public.order_addons (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id),
  addon_id bigint not null references public.addons (id),
  addon_name text not null,
  unit_price numeric(12, 2) not null,
  quantity integer not null check (quantity between 1 and 1000),
  total numeric(12, 2) generated always as (unit_price * quantity) stored,
  unique (order_id, addon_id)
);

create table public.order_payments (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique,
  order_id uuid not null unique references public.orders (id),
  amount numeric(12, 2) not null check (amount > 0 and amount < 10000000000),
  method text not null check (method in ('cash', 'gcash', 'other')),
  recorded_at timestamptz not null default clock_timestamp(),
  recorded_by uuid not null,
  recorded_by_email text
);

create index order_payments_recorded_idx on public.order_payments (recorded_at, id);

create table public.order_audit (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id),
  action text not null check (action in ('created', 'edited', 'done', 'released', 'cancelled', 'paid')),
  reason text,
  recorded_at timestamptz not null default clock_timestamp(),
  recorded_by uuid not null,
  recorded_by_email text
);

create index order_audit_order_idx on public.order_audit (order_id, id);

create table laundry_private.order_save_requests (
  request_id uuid primary key,
  actor_id uuid not null,
  payload_hash bytea not null,
  order_id uuid references public.orders (id)
);

create function public.get_staff_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select role from public.staff_profiles where user_id = auth.uid() and active
$$;

alter table public.staff_profiles enable row level security;
alter table public.services enable row level security;
alter table public.addons enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.order_addons enable row level security;
alter table public.order_payments enable row level security;
alter table public.order_audit enable row level security;
alter table laundry_private.order_save_requests enable row level security;

revoke all on table public.staff_profiles, public.services, public.addons, public.orders,
  public.order_items, public.order_addons, public.order_payments, public.order_audit
  from public, anon, authenticated;
revoke all on sequence public.services_id_seq, public.addons_id_seq, public.order_items_id_seq,
  public.order_addons_id_seq, public.order_audit_id_seq, laundry_private.claim_numbers
  from public, anon, authenticated;
grant select on table public.staff_profiles, public.services, public.addons, public.orders,
  public.order_items, public.order_addons, public.order_payments, public.order_audit
  to authenticated;

create policy staff_profiles_read on public.staff_profiles for select to authenticated
  using ((select public.get_staff_role()) = 'manager' or (user_id = (select auth.uid()) and active));
create policy services_read on public.services for select to authenticated
  using ((select public.get_staff_role()) is not null);
create policy addons_read on public.addons for select to authenticated
  using ((select public.get_staff_role()) is not null);
create policy orders_read on public.orders for select to authenticated
  using ((select public.get_staff_role()) is not null);
create policy order_items_read on public.order_items for select to authenticated
  using ((select public.get_staff_role()) is not null);
create policy order_addons_read on public.order_addons for select to authenticated
  using ((select public.get_staff_role()) is not null);
create policy order_payments_read on public.order_payments for select to authenticated
  using ((select public.get_staff_role()) = 'manager');
create policy order_audit_read on public.order_audit for select to authenticated
  using ((select public.get_staff_role()) = 'manager');

create function laundry_private.require_staff()
returns uuid
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if public.get_staff_role() is null then
    raise exception 'An active staff account is required.' using errcode = '42501';
  end if;
  return auth.uid();
end;
$$;

create function laundry_private.audit_order(p_order_id uuid, p_action text, p_reason text default null)
returns void
language sql
set search_path = ''
as $$
  insert into public.order_audit (order_id, action, reason, recorded_by, recorded_by_email)
  values (p_order_id, p_action, p_reason, auth.uid(), auth.jwt()->>'email')
$$;

create function public.record_order_payment(p_order_id uuid, p_request_id uuid, p_method text, p_expected_total numeric)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_id uuid := laundry_private.require_staff();
  target_order public.orders%rowtype;
  existing_payment public.order_payments%rowtype;
  payment_id uuid;
begin
  if p_request_id is null or p_method is null or p_method not in ('cash', 'gcash', 'other') or p_expected_total is null then
    raise exception 'A valid payment method and request ID are required.' using errcode = '22023';
  end if;

  select * into target_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order not found.' using errcode = 'P0002';
  end if;

  select * into existing_payment from public.order_payments where request_id = p_request_id;
  if found then
    if existing_payment.order_id <> p_order_id or existing_payment.recorded_by <> actor_id
        or existing_payment.method <> p_method or existing_payment.amount <> p_expected_total then
      raise exception 'Payment request does not match the original payment.' using errcode = '22023';
    end if;
    return existing_payment.id;
  end if;

  if target_order.status in ('cancelled', 'released') or target_order.payment_status then
    raise exception 'This order cannot accept another payment.' using errcode = '22023';
  end if;
  if target_order.total <> p_expected_total then
    raise exception 'The amount due changed. Refresh the order and confirm the new total.' using errcode = '22023';
  end if;

  insert into public.order_payments (request_id, order_id, amount, method, recorded_by, recorded_by_email)
  values (p_request_id, p_order_id, target_order.total, p_method, actor_id, auth.jwt()->>'email')
  returning id into payment_id;
  update public.orders set payment_status = true, updated_at = clock_timestamp() where id = p_order_id;
  perform laundry_private.audit_order(p_order_id, 'paid');
  return payment_id;
end;
$$;

create function public.save_order(
  p_request_id uuid,
  p_order_id uuid,
  p_customer_name text,
  p_customer_phone text,
  p_pickup_at timestamptz,
  p_notes text,
  p_items jsonb,
  p_addons jsonb,
  p_payment_method text,
  p_expected_total numeric,
  p_expected_updated_at timestamptz
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  acting_user uuid := laundry_private.require_staff();
  target_order public.orders%rowtype;
  existing_request laundry_private.order_save_requests%rowtype;
  order_uuid uuid;
  request_hash bytea;
  normalized_name text := btrim(p_customer_name);
  normalized_phone text := nullif(btrim(p_customer_phone), '');
  normalized_notes text := nullif(btrim(p_notes), '');
  item_count integer;
  addon_count integer;
  item_snapshot jsonb;
  addon_snapshot jsonb;
  item_total numeric;
  addon_total numeric;
begin
  if p_request_id is null or normalized_name is null or char_length(normalized_name) not between 1 and 120
      or char_length(normalized_phone) > 40 or char_length(normalized_notes) > 2000 or p_expected_total is null then
    raise exception 'Enter a customer name and valid order details.' using errcode = '22023';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_typeof(p_addons) is distinct from 'array' then
    raise exception 'Services and add-ons must be lists.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) not between 1 and 100 or jsonb_array_length(p_addons) > 100 then
    raise exception 'Select at least one service and up to 100 services or add-ons per order.' using errcode = '22023';
  end if;
  if p_payment_method is not null and (p_order_id is not null or p_payment_method not in ('cash', 'gcash', 'other')) then
    raise exception 'Select a valid payment method for a new order.' using errcode = '22023';
  end if;

  request_hash := sha256(convert_to(jsonb_build_array(
    p_order_id, normalized_name, normalized_phone, extract(epoch from p_pickup_at), normalized_notes,
    p_items, p_addons, p_payment_method, trim_scale(p_expected_total), extract(epoch from p_expected_updated_at)
  )::text, 'UTF8'));
  insert into laundry_private.order_save_requests (request_id, actor_id, payload_hash)
  values (p_request_id, acting_user, request_hash) on conflict (request_id) do nothing;
  if not found then
    select * into existing_request from laundry_private.order_save_requests where request_id = p_request_id;
    if existing_request.actor_id <> acting_user or existing_request.payload_hash <> request_hash then
      raise exception 'Order request does not match the original save.' using errcode = '22023';
    end if;
    return existing_request.order_id;
  end if;

  if p_order_id is not null then
    select * into target_order from public.orders where id = p_order_id for update;
    if not found then
      raise exception 'Order not found.' using errcode = 'P0002';
    end if;
    if target_order.status not in ('pending', 'done') or target_order.payment_status then
      raise exception 'Only unpaid, unreleased orders can be edited.' using errcode = '22023';
    end if;
    if target_order.updated_at is distinct from p_expected_updated_at then
      raise exception 'This order changed. Reopen it before saving.' using errcode = '22023';
    end if;
  end if;

  -- Preserve prices and names for existing lines. Use active catalog values for newly added lines.
  select count(*), jsonb_agg(jsonb_build_object('id', s.id, 'quantity', i.quantity,
    'name', coalesce(old.service_name, s.name), 'price', coalesce(old.price, s.price))),
    sum(coalesce(old.price, s.price) * i.quantity)
  into item_count, item_snapshot, item_total
  from jsonb_to_recordset(p_items) as i(id bigint, quantity integer)
  join public.services s on s.id = i.id
  left join public.order_items old on old.order_id = p_order_id and old.service_id = s.id
  where (old.id is not null or s.is_active) and i.quantity between 1 and 1000;

  select count(*), jsonb_agg(jsonb_build_object('id', a.id, 'quantity', i.quantity,
    'name', coalesce(old.addon_name, a.name), 'price', coalesce(old.unit_price, a.price))),
    coalesce(sum(coalesce(old.unit_price, a.price) * i.quantity), 0)
  into addon_count, addon_snapshot, addon_total
  from jsonb_to_recordset(p_addons) as i(id bigint, quantity integer)
  join public.addons a on a.id = i.id
  left join public.order_addons old on old.order_id = p_order_id and old.addon_id = a.id
  where (old.id is not null or a.is_active) and i.quantity between 1 and 1000;

  if item_count <> jsonb_array_length(p_items) or addon_count <> jsonb_array_length(p_addons) then
    raise exception 'Check service and add-on availability and quantities.' using errcode = '22023';
  end if;
  if item_total + addon_total <> p_expected_total then
    raise exception 'The price changed. Reopen the order form and confirm the new total.' using errcode = '22023';
  end if;

  if p_order_id is null then
    insert into public.orders (customer_name, customer_phone, pickup_at, notes, total, created_by, created_by_email)
    values (normalized_name, normalized_phone, p_pickup_at, normalized_notes, item_total + addon_total,
      acting_user, auth.jwt()->>'email')
    returning id into order_uuid;
    perform laundry_private.audit_order(order_uuid, 'created');
  else
    order_uuid := p_order_id;
    update public.orders set customer_name = normalized_name, customer_phone = normalized_phone, pickup_at = p_pickup_at,
      notes = normalized_notes, total = item_total + addon_total, updated_at = clock_timestamp()
    where id = order_uuid;
    delete from public.order_addons where order_id = order_uuid;
    delete from public.order_items where order_id = order_uuid;
    perform laundry_private.audit_order(order_uuid, 'edited');
  end if;

  insert into public.order_items (order_id, service_id, service_name, price, quantity)
  select order_uuid, i.id, i.name, i.price, i.quantity
  from jsonb_to_recordset(item_snapshot) as i(id bigint, name text, price numeric, quantity integer);
  insert into public.order_addons (order_id, addon_id, addon_name, unit_price, quantity)
  select order_uuid, a.id, a.name, a.price, a.quantity
  from jsonb_to_recordset(coalesce(addon_snapshot, '[]')) as a(id bigint, name text, price numeric, quantity integer);

  if p_payment_method is not null then
    perform public.record_order_payment(order_uuid, p_request_id, p_payment_method, p_expected_total);
  end if;

  update laundry_private.order_save_requests set order_id = order_uuid where request_id = p_request_id;
  return order_uuid;
end;
$$;

create function public.advance_order(p_order_id uuid, p_status text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_order public.orders%rowtype;
begin
  perform laundry_private.require_staff();
  if p_status is null or p_status not in ('done', 'released') then
    raise exception 'Select a valid next status.' using errcode = '22023';
  end if;
  select * into target_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order not found.' using errcode = 'P0002';
  end if;
  if target_order.status = p_status then
    return p_order_id;
  end if;
  if not ((p_status = 'done' and target_order.status = 'pending')
       or (p_status = 'released' and target_order.status = 'done' and target_order.payment_status)) then
    raise exception 'Finish the laundry and collect payment before release.' using errcode = '22023';
  end if;
  update public.orders set status = p_status, updated_at = clock_timestamp() where id = p_order_id;
  perform laundry_private.audit_order(p_order_id, p_status);
  return p_order_id;
end;
$$;

create function public.void_order(p_order_id uuid, p_reason text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_order public.orders%rowtype;
  normalized_reason text := btrim(p_reason);
begin
  if public.get_staff_role() is distinct from 'manager' then
    raise exception 'A manager account is required to void an order.' using errcode = '42501';
  end if;
  if normalized_reason is null or char_length(normalized_reason) not between 1 and 500 then
    raise exception 'Enter a reason for voiding the order.' using errcode = '22023';
  end if;
  select * into target_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Order not found.' using errcode = 'P0002';
  end if;
  if target_order.status = 'cancelled' then
    return p_order_id;
  end if;
  if target_order.status = 'released' or target_order.payment_status then
    raise exception 'Paid or released orders cannot be voided.' using errcode = '22023';
  end if;
  update public.orders set status = 'cancelled', updated_at = clock_timestamp() where id = p_order_id;
  perform laundry_private.audit_order(p_order_id, 'cancelled', normalized_reason);
  return p_order_id;
end;
$$;

